def chinese_spec(text: str) -> str:
    translated = _SPEC.sub(lambda match: SPEC_ZH[match[0]], text)
    units = {
        "枚": "片",
        "本": "支",
        "缶": "罐",
        "貫": "贯",
        "食": "份",
        "切": "片",
        "コ": "个",
        "個": "个",
        "錠": "片",
        "尾": "条",
        "組": "组",
        "入": "装",
    }
    return re.sub(
        r"(?<=\d)([枚本缶貫食切コ個錠尾組])(入)?",
        lambda m: units[m[1]] + ("装" if m[2] else ""),
        translated,
    )


def localized_spec(text: str) -> str:
    return text if LANGUAGE.get() == "ja" else chinese_spec(text)


def localized_note(text: str) -> str:
    if LANGUAGE.get() == "zh":
        return localized_spec(text)
    text = re.sub(r"每人限\s*(\d+)\s*件", r"お一人様\1点限り", text)
    text = re.sub(r"(\d\d:\d\d) 起", r"\1から", text)
    return (
        text.replace("开店至12:00", "開店〜12時")
        .replace("已结束", "終了")
        .replace("预约商品。締切", "予約商品。締切")
        .replace("合计每人限", "お一人様合計")
        .replace(" · 共300件", "・合計300点")
        .replace("每人限1箱", "お一人様1箱限り")
        .replace("索引未给出计价规格", "検索インデックスに価格単位の記載なし")
        .replace("页面写当日限り，索引未给出日历日期", "当日限り。掲載日未確認")
    )
