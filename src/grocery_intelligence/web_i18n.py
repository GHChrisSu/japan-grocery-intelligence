def tr(message: str, **values) -> str:
    template = JA.get(message, message) if LANGUAGE.get() == "ja" else message
    return template.format(**values) if values else template


@cache
def product_translations() -> dict[str, str]:
    path = Path(__file__).parent / "assets" / "products-zh.json"
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RuntimeError("Could not read bundled product translations") from exc


def chinese_product(name: str) -> str:
    return product_translations().get(name, name)


def product_name(name: str) -> str:
    return name if LANGUAGE.get() == "ja" else chinese_product(name)


def store_name(name: str) -> str:
    return name if LANGUAGE.get() == "ja" else STORES_ZH.get(name, name)


